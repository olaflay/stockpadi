import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const scriptDirectory = dirname(fileURLToPath(import.meta.url));
const sourcePath = resolve(scriptDirectory, "../../packages/contracts/src/index.ts");
const targetPath = resolve(scriptDirectory, "../src/shared/contracts.generated.ts");
const source = await readFile(sourcePath, "utf8");

await mkdir(dirname(targetPath), { recursive: true });
await writeFile(
  targetPath,
  `// Generated from packages/contracts/src/index.ts. Do not edit this file directly.\n${source}`,
  "utf8",
);
