import { existsSync } from "node:fs";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const scriptDirectory = dirname(fileURLToPath(import.meta.url));
const sourcePath = resolve(scriptDirectory, "../../packages/contracts/src/index.ts");
const environmentSourcePath = resolve(scriptDirectory, "../../packages/contracts/src/environment.ts");
const environmentContractSourcePath = resolve(scriptDirectory, "../../packages/contracts/src/environment-contract.json");
const targetPath = resolve(scriptDirectory, "../src/shared/contracts.generated.ts");
const environmentTargetPath = resolve(scriptDirectory, "../src/shared/environment.ts");
const environmentContractTargetPath = resolve(scriptDirectory, "../src/shared/environment-contract.json");
if (!existsSync(sourcePath)) {
  if (!existsSync(targetPath)) {
    throw new Error(
      `Shared contracts source is unavailable at ${sourcePath}, and the generated fallback is missing at ${targetPath}.`,
    );
  }

  console.warn("Shared contracts source is outside this deployment bundle; using the checked-in generated fallback.");
} else {
  const source = await readFile(sourcePath, "utf8");

  await mkdir(dirname(targetPath), { recursive: true });
  await writeFile(
    targetPath,
    `// Generated from packages/contracts/src/index.ts. Do not edit this file directly.\n${source}`,
    "utf8",
  );
  await writeFile(environmentTargetPath, await readFile(environmentSourcePath, "utf8"), "utf8");
  await writeFile(environmentContractTargetPath, await readFile(environmentContractSourcePath, "utf8"), "utf8");
}
